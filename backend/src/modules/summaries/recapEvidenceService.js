function createExtras() {
  return { wides: 0, noBalls: 0, byes: 0, legByes: 0, penaltyRuns: 0 };
}

function deliveryReference(delivery) {
  return {
    deliveryId: delivery.id,
    inningsId: delivery.inningsId,
    inningsNumber: delivery.innings.inningsNumber,
    deliverySequence: delivery.deliverySequence,
    display: {
      overNumber: delivery.displayOver,
      ballLabel: delivery.displayBallLabel
    }
  };
}

function playerContribution(contributions, player, property, amount) {
  const current = contributions[player.id] ?? {
    playerId: player.id,
    name: player.displayName,
    [property]: 0
  };
  current[property] += amount;
  contributions[player.id] = current;
}

function notableEvents(deliveries) {
  const events = [];
  for (const delivery of deliveries) {
    const reference = deliveryReference(delivery);
    for (const wicket of delivery.wickets) {
      if (wicket.countsAsWicket) {
        events.push({
          type: 'WICKET',
          playerOut: wicket.playerOut.displayName,
          kind: wicket.kind,
          reference
        });
      }
    }
    if (delivery.batterRuns === 4 || delivery.batterRuns === 6) {
      events.push({
        type: delivery.batterRuns === 4 ? 'FOUR' : 'SIX',
        batter: delivery.batter.displayName,
        runs: delivery.batterRuns,
        reference
      });
    }
  }
  return events.slice(-20);
}

/**
 * Creates factual recap evidence. The result deliberately contains no natural
 * language generated by a model and can be returned alongside narration.
 */
export function buildRecapEvidence({ matchId, deliveries, window }) {
  const extras = createExtras();
  const batters = {};
  const bowlers = {};
  let runs = 0;
  let wickets = 0;
  let fours = 0;
  let sixes = 0;
  let dots = 0;

  for (const delivery of deliveries) {
    runs += delivery.totalRuns;
    wickets += delivery.wickets.filter((wicket) => wicket.countsAsWicket).length;
    if (delivery.totalRuns === 0) dots += 1;
    if (delivery.batterRuns === 4) fours += 1;
    if (delivery.batterRuns === 6) sixes += 1;
    extras.wides += delivery.wides;
    extras.noBalls += delivery.noBalls;
    extras.byes += delivery.byes;
    extras.legByes += delivery.legByes;
    extras.penaltyRuns += delivery.penaltyRuns;
    playerContribution(batters, delivery.batter, 'runs', delivery.batterRuns);
    playerContribution(
      bowlers,
      delivery.bowler,
      'runsConceded',
      delivery.totalRuns - delivery.byes - delivery.legByes - delivery.penaltyRuns
    );
  }

  const sortBy = (property) => (left, right) =>
    right[property] - left[property] || left.name.localeCompare(right.name);
  return {
    type: 'CATCH_ME_UP_EVIDENCE',
    matchId,
    window: {
      type: window.type,
      timestampQuality: window.timestampQuality,
      anchor: window.anchor,
      overRange: window.overRange,
      deliveryRange: window.deliveryRange
    },
    totals: { runs, wickets, fours, sixes, dots, extras },
    contributors: {
      batters: Object.values(batters).sort(sortBy('runs')).slice(0, 5),
      bowlers: Object.values(bowlers).sort(sortBy('runsConceded')).slice(0, 5)
    },
    notableEvents: notableEvents(deliveries),
    references: deliveries.map(deliveryReference)
  };
}

/** Limits model context while preserving the response's deterministic facts. */
export function recapNarrationContext(evidence) {
  return {
    window: evidence.window,
    totals: evidence.totals,
    contributors: evidence.contributors,
    notableEvents: evidence.notableEvents
  };
}
